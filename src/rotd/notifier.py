"""Message rendering and budget-aware delivery (build prompt §14.1).

Every message is defined here so the wording is reviewable in one place. Messages
are rendered from a decision object, never from prose generated by a model.

Message types:
- ``IGNITION``  — the alert that spends budget. Explains *why now* in one line.
- ``BOARD``     — the silent scheduled board (§11 A6).
- ``ABORT``     — a fired alert that has been cancelled, with the reason code.
- ``ROTD``      — the day's qualified runner (rank 1 at/above ``ROTD_MIN_SCORE``).
- ``MISS_REPORT`` — the daily post-mortem (§12.4).

Times are shown in both ET and KL (§18.5). Prices render with up to four decimals.
"""

from __future__ import annotations

import logging
from datetime import datetime
from typing import Any, Optional

from .config import Config
from .scoring import Scored
from .state_machine import State, Transition
from .util import (age_str, compact, money, now_utc, num, pct, price_str,
                   to_et, to_kl)

log = logging.getLogger(__name__)


def _when(dt: Optional[datetime]) -> str:
    dt = dt or now_utc()
    return f"{to_et(dt):%Y-%m-%d %H:%M:%S} ET / {to_kl(dt):%H:%M} KL"


def _price_line(rec: Any, mode: str) -> str:
    """Price line. POST shows the extended-hours move against today's 16:00 close."""
    ah = getattr(rec, "ah_change_pct", None)
    if mode == "POST" and ah is not None:
        return (f"Price ${price_str(rec.price)} "
                f"({pct(ah)} AH | {pct(rec.change_pct)} vs prev close)")
    return f"Price ${price_str(rec.price)} ({pct(rec.change_pct)} vs prev close)"


def render_ignition(symbol: str, scored: Scored, rec: Any, slot: str, mode: str,
                    reasons: list[str], now: Optional[datetime] = None) -> str:
    """The ignition alert. One screen: what, why-now, the numbers, the risk."""
    lines = [
        f"🚨 ROTD IGNITION — ${symbol}",
        f"{_when(now)}  |  mode {mode}  |  slot {slot}",
        "",
        f"Score {scored.score:.0f}/100  (rank {scored.rank or '-'})",
    ]
    if rec is not None:
        lines.append(_price_line(rec, mode))
        lines.append(
            f"Spread {num(rec.spread_pct)}%   Vol {compact(rec.volume)}   "
            f"Dollar-vol {money(rec.dollar_volume)}")
        # The tape that actually fired the alert, next to the whole-day totals.
        tape: list[str] = []
        if getattr(rec, "vol_3m", None) is not None:
            tape.append(f"3m Vol {compact(rec.vol_3m)}")
        if getattr(rec, "dollar_volume_10m", None) is not None:
            tape.append(f"10m Dollar-Vol {money(rec.dollar_volume_10m)}")
        if tape:
            lines.append("   ".join(tape))
        if rec.shares_float:
            lines.append(f"Float {compact(rec.shares_float)}   "
                         f"Short {num(rec.short_float)}%")
    # Component breakdown, worst first, so the weakest link is visible.
    comps = sorted(scored.components.items(), key=lambda kv: kv[1].points, reverse=True)
    lines.append("")
    lines.append("Why now:")
    for name, c in comps:
        raw = "n/a" if c.raw is None else f"{c.raw:.2f}"
        lines.append(f"  {name:<9} {c.points:>4.1f}/{c.weight:.0f}  (raw {raw})")
    if reasons:
        lines.append("")
        lines.append("Flags: " + ", ".join(reasons))
    lines.append("")
    lines.append("Risk: this is decision support, not advice; runners reverse hard.")
    return "\n".join(lines)


def render_board(board: list[Scored], mode: str, data_grade: str,
                 records: dict[str, Any], now: Optional[datetime] = None) -> str:
    """The silent scheduled board."""
    if not board:
        return (f"📋 ROTD BOARD — none\n{_when(now)}  |  mode {mode}  |  "
                f"data {data_grade}\n(no qualified candidates this cycle)")
    lines = [f"📋 ROTD BOARD — top {len(board)}",
             f"{_when(now)}  |  mode {mode}  |  data {data_grade}", ""]
    for c in board:
        rec = records.get(c.symbol)
        px = price_str(rec.price) if rec else "n/a"
        ch = pct(rec.change_pct) if rec else "n/a"
        lines.append(f"  {c.rank}. ${c.symbol:<6} {c.score:>5.1f}   {px:>8}  {ch}")
    return "\n".join(lines)


def render_abort(symbol: str, t: Transition, rec: Any, now: Optional[datetime] = None) -> str:
    lines = [f"⚠️ ROTD ABORT — ${symbol}",
             f"{_when(now)}  |  reason {t.reason}", ""]
    lines.append(t.detail or "the ignition condition no longer holds")
    if rec is not None and rec.price is not None:
        lines.append(f"Price now {price_str(rec.price)}")
    return "\n".join(lines)


def render_rotd(symbol: str, scored: Scored, rec: Any, now: Optional[datetime] = None) -> str:
    lines = [f"🏆 ROTD — ${symbol}",
             f"{_when(now)}  |  score {scored.score:.0f}/100", ""]
    if rec is not None:
        lines.append(f"Price {price_str(rec.price)}  ({pct(rec.change_pct)})")
        if rec.company:
            lines.append(rec.company)
    return "\n".join(lines)


def render_miss_report(report: dict[str, Any]) -> str:
    """The daily MISS REPORT (§12.4). Always produced, even on a zero-alert day."""
    day = report.get("trading_day", "?")
    lines = [f"📊 ROTD MISS REPORT — {day}",
             f"alerts {report.get('n_alerts', 0)}  |  "
             f"runners in list {report.get('n_runners', 0)}  |  "
             f"caught {report.get('n_caught', 0)}  |  "
             f"missed {report.get('n_missed', 0)}", ""]
    lines.append(f"Data grade for the day: {report.get('data_grade', '?')}"
                 f"  (mean {report.get('mean_grade', '?')})")
    hits = report.get("hits", [])
    if hits:
        lines.append("")
        lines.append("Caught:")
        for h in hits:
            lines.append(f"  ✓ ${h['symbol']:<6} lead {h.get('lead', 'n/a')}  "
                         f"max {pct(h.get('max_gain_pct'))}")
    misses = report.get("misses", [])
    if misses:
        lines.append("")
        lines.append("Missed runners (and why):")
        for m in misses:
            lines.append(f"  ✗ ${m['symbol']:<6} {pct(m.get('gain_pct'))}  "
                         f"— {m.get('why', 'unknown')}")
    false_pos = report.get("false_positive", [])
    if false_pos:
        lines.append("")
        lines.append("Alerts that did not run:")
        for f in false_pos:
            lines.append(f"  · ${f['symbol']:<6} — {f.get('why', 'reversed')}")
    not_enforced = report.get("not_enforced_gates", [])
    if not_enforced:
        lines.append("")
        lines.append("Gates NOT ENFORCED today (no feed supplies their input — VERIFIED G-18):")
        for g in not_enforced:
            lines.append(f"  · {g}")
    if not (hits or misses or false_pos):
        lines.append("")
        lines.append("Quiet day: no sub-$10 names ran, and ROTD stayed silent. "
                     "That is a correct outcome, not a failure.")
    return "\n".join(lines)


